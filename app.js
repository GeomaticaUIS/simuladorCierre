function getDurations(site, scenario) {
  const a = DATA.aa[site.aa];
  let aaMean = a ? Number(a.medio || a.plazo || 0) : 0,
    aaMin = a ? Number(a.minimo || a.plazo || 0) : aaMean,
    aaMax = a ? Math.max(Number(a.plazo || 0), Number(a.medio || 0), Number(a.minimo || 0)) : aaMean;
  const key = transitKey(site.at),
    t = key ? DATA.at[key] : null;
  let tm = t ? Number(t.medio) : 0,
    tmin = t ? Number(t.minimo) : tm,
    tmax = t ? Number(t.maximo) : tm;
  let aaPick = scenario === 'optimista' ? aaMin : scenario === 'pesimista' ? aaMax : aaMean;
  let tPick = scenario === 'optimista' ? tmin : scenario === 'pesimista' ? tmax : tm;
  let aaFactor = aaMean > 0 ? aaPick / aaMean : 1,
    totalMean = aaMean + tm,
    totalPick = aaPick + tPick;
  return {
    aaFactor,
    totalFactor: totalMean > 0 ? totalPick / totalMean : 1
  };
}

function projectFromCutoff(date, factor, opt) {
  if (!date) return null;
  const remaining = Math.max(0, diff(date, DATA.cutoff));
  if (!remaining) return date;
  return add(DATA.cutoff, Math.round(remaining * factor * (1 - Number(opt || 0) / 100)));
}

function clampInst(raw) {
  const f = FLOOR_DATE();
  return raw && raw < f ? {
    d: f,
    clamped: true
  } : {
    d: raw,
    clamped: false
  }
}

function calc(site) {
  const r = calc0(site);
  const k = clampInst(r.inst);
  const base = r.base.inst;
  return {
    ...r,
    inst: k.d,
    clamped: k.clamped,
    rawInst: r.inst,
    delta: diff(k.d, base)
  }
}

function calc0(site) {
  let s = byId('scenario').value,
    opt = Number(byId('optimization').value),
    decision = Number(byId('decisionDelay').value || 0),
    rel = Number(byId('relocationDelay').value || 0),
    instAdj = Number(byId('installAdjust').value || 0);
  let d = getDurations(site, s),
    extra = decision + (site.estado.toLowerCase().includes('relocaliz') ? rel : 0) + (adj[site.instalacion] || 0);
  let poc = projectFromCutoff(site.poc, d.aaFactor, opt),
    acor = projectFromCutoff(site.acor, d.totalFactor, opt),
    inst = projectFromCutoff(site.instalacion_proj, d.totalFactor, opt);
  return {
    poc: add(poc, extra),
    acor: add(acor, extra),
    inst: add(inst, extra + instAdj),
    base: {
      poc: site.poc,
      acor: site.acor,
      inst: site.instalacion_proj
    },
    delta: diff(inst, site.instalacion_proj) + extra + instAdj
  };
}

